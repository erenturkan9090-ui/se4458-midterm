# ARM calls go through Invoke-RestMethod with a token from az, not `az rest`: APIM policy
# responses start with a UTF-8 BOM and `az rest` crashes printing them on a cp1254 console.
$script:ArmToken = $null
function Invoke-Arm([string]$method, [string]$path, $body) {
  if (-not $script:ArmToken) {
    $script:ArmToken = Invoke-Az account get-access-token --resource https://management.azure.com/ --query accessToken -o tsv
  }
  $params = @{
    Method  = $method
    Uri     = "$ApimUrl$path`?api-version=$ArmApi"
    Headers = @{ Authorization = "Bearer $($script:ArmToken)" }
  }
  if ($null -ne $body) {
    $params.ContentType = "application/json; charset=utf-8"
    $params.Body = [System.Text.Encoding]::UTF8.GetBytes(($body | ConvertTo-Json -Depth 10))
  }
  try { return Invoke-RestMethod @params }
  catch {
    $detail = $_.ErrorDetails.Message
    throw "ARM $method $path failed: $($_.Exception.Message) $detail"
  }
}
function Invoke-ArmPut([string]$path, $body) {
  Write-Host "  PUT $path"
  Invoke-Arm "PUT" $path $body | Out-Null
}

if ($StepList -contains "apim") {
  New-Item -ItemType Directory -Force $BuildDir | Out-Null
  Write-Step "API Management $Apim (Consumption) - first creation takes a few minutes"
  if (-not (Test-Az apim show -g $ResourceGroup -n $Apim --query id)) {
    Invoke-Az apim create -g $ResourceGroup -n $Apim -l $ApimLocation --sku-name Consumption `
      --publisher-email $PublisherEmail --publisher-name "SE4458 Billing" -o none
  }

  Write-Step "Named value, version set, API, operations, policies"
  $jwtKeyB64 = [Convert]::ToBase64String([System.Text.Encoding]::UTF8.GetBytes($JwtSecret))
  Invoke-ArmPut "/namedValues/jwt-signing-key" @{ properties = @{ displayName = "jwt-signing-key"; value = $jwtKeyB64; secret = $true } }
  Invoke-ArmPut "/apiVersionSets/billing" @{ properties = @{ displayName = "Billing API"; versioningScheme = "Segment" } }
  Invoke-ArmPut "/apis/billing-v1" @{ properties = @{
      displayName = "Billing API"; path = "billing"; apiVersion = "v1"; apiVersionSetId = "$ApimId/apiVersionSets/billing"
      serviceUrl = "https://$ApiApp.azurewebsites.net/api/v1"; protocols = @("https"); subscriptionRequired = $true
      subscriptionKeyParameterNames = @{ header = "Ocp-Apim-Subscription-Key"; query = "subscription-key" }
      description = "Mobile provider Billing REST API, published through the gateway" } }

  # Operations come from the same route table the local gateway uses.
  # Run through cmd with stdin from NUL: started from a piped/background shell, npx otherwise
  # waits on the inherited stdin and never returns.
  $routesFile = Join-Path $BuildDir "routes.json"
  Push-Location $RepoRoot
  try {
    & cmd.exe /c "npx tsx infra/azure/print-routes.ts < NUL > `"$routesFile`""
    if ($LASTEXITCODE -ne 0) { throw "could not read the gateway route table" }
  } finally { Pop-Location }
  $routes = [System.IO.File]::ReadAllText($routesFile) | ConvertFrom-Json
  # ReadAllText, not Get-Content -Raw: on PS 5.1 the latter attaches PSPath/PSProvider note
  # properties to the string, and ConvertTo-Json -Depth 10 then walks the provider object graph
  # and never finishes.
  $apiPolicy = [System.IO.File]::ReadAllText((Join-Path $RepoRoot "gateway\apim\api-policy.xml"))
  $protectedPolicy = [System.IO.File]::ReadAllText((Join-Path $RepoRoot "gateway\apim\protected-operation-policy.xml"))
  Invoke-ArmPut "/apis/billing-v1/policies/policy" @{ properties = @{ format = "rawxml"; value = $apiPolicy } }
  foreach ($r in $routes) {
    $params = @()
    foreach ($m in [regex]::Matches($r.path, '\{([^}]+)\}')) {
      $params += @{ name = $m.Groups[1].Value; type = "string"; required = $true }
    }
    Invoke-ArmPut "/apis/billing-v1/operations/$($r.id)" @{ properties = @{
        displayName = $r.description; method = $r.method; urlTemplate = $r.path; templateParameters = $params } }
    if ($r.protected) {
      Invoke-ArmPut "/apis/billing-v1/operations/$($r.id)/policies/policy" @{ properties = @{ format = "rawxml"; value = $protectedPolicy } }
    }
    Write-Host ("  {0,-5} /billing/v1{1}{2}" -f $r.method, $r.path, $(if ($r.protected) { "   [JWT]" } else { "" }))
  }

  Write-Step "Subscription key for the agent"
  Invoke-ArmPut "/subscriptions/billing-agent" @{ properties = @{ displayName = "Billing agent"; scope = "$ApimId/apis/billing-v1"; state = "active" } }
  $secrets = Invoke-Arm "POST" "/subscriptions/billing-agent/listSecrets" $null
  $State["GATEWAY_SUBSCRIPTION_KEY"] = $secrets.primaryKey
}


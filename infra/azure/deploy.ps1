<#
.SYNOPSIS
  Deploys the SE4458 Billing system to Azure (Windows PowerShell 5.1 compatible).

  Resources (one resource group):
    - Azure Database for PostgreSQL Flexible Server (Burstable B1ms) + database "billing"
    - Linux App Service plan (F1 by default) with two web apps: Billing API and MCP server
    - Azure API Management (Consumption) publishing the Billing API at /billing/v1

  Re-runnable: names and generated secrets are kept in <repo>/.env.azure (git-ignored),
  and every step skips resources that already exist.

.EXAMPLE
  az login
  powershell -ExecutionPolicy Bypass -File infra\azure\deploy.ps1 -Location swedencentral
#>

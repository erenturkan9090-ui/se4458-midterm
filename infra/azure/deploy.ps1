function Write-Step([string]$msg) { Write-Host "`n=== $msg" -ForegroundColor Cyan }

# Runs az and returns stdout; throws on a non-zero exit code.
# On PowerShell 5.1, native stderr (az warnings/progress) becomes an ErrorRecord that
# "Stop" turns into a terminating error, so stderr is captured and printed instead.
function Invoke-Az {
  $ErrorActionPreference = "Continue"
  $stdout = @()
  & az @args 2>&1 | ForEach-Object {
    if ($_ -is [System.Management.Automation.ErrorRecord]) { Write-Host $_.Exception.Message -ForegroundColor DarkGray }
    else { $stdout += $_ }
  }
  # Only the command words go into the message: the full argument list can contain secrets.
  if ($LASTEXITCODE -ne 0) { throw "az $(($args | Select-Object -First 3) -join ' ') ... failed (exit $LASTEXITCODE)" }
  return $stdout
}
# Runs az and returns $true/$false instead of throwing (used for "does it exist?" checks).
function Test-Az {
  $ErrorActionPreference = "Continue"
  & az @args 2>&1 | Out-Null
  return ($LASTEXITCODE -eq 0)
}

# Runs a native command (npm, npx, tar) so its stderr is shown, not turned into a terminating error.
# Returns stdout lines; the caller checks $LASTEXITCODE.
function Invoke-Native {
  $ErrorActionPreference = "Continue"
  $exe = $args[0]
  $rest = @($args | Select-Object -Skip 1)
  & $exe @rest 2>&1 | ForEach-Object {
    if ($_ -is [System.Management.Automation.ErrorRecord]) { Write-Host $_.Exception.Message -ForegroundColor DarkGray }
    else { $_ }
  }
}

function New-Secret([int]$length, [string]$alphabet) {
  $bytes = New-Object byte[] $length
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  -join ($bytes | ForEach-Object { $alphabet[$_ % $alphabet.Length] })
}

# ---------- state (names + secrets) ----------
$State = @{}
if (Test-Path $StateFile) {
  # -cmatch, not -match: case-insensitive matching under the Turkish culture lowercases "I" to
  # dotless "ı", so keys like AZ_SUFFIX would silently fail to match [A-Z].
  foreach ($line in (Get-Content $StateFile)) {
    if ($line -cmatch '^\s*([A-Z0-9_]+)=(.*)$') { $State[$Matches[1]] = $Matches[2] }
  }
}
function Get-State([string]$key, [scriptblock]$init) {
  if (-not $State.ContainsKey($key) -or -not $State[$key]) { $State[$key] = & $init }
  return $State[$key]
}
function Save-State {
  $lines = @("# Generated by infra/azure/deploy.ps1 - contains secrets, never commit.")
  foreach ($k in ($State.Keys | Sort-Object)) { $lines += "$k=$($State[$k])" }
  Set-Content -Path $StateFile -Value $lines -Encoding ASCII
}


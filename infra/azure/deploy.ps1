# ---------- Build + zip deploy ----------
function Publish-Service([string]$workspace, [string]$srcDir, [string[]]$extraDirs, [string]$app) {
  Write-Step "Build + deploy $workspace -> $app"
  Push-Location $RepoRoot
  try {
    Invoke-Native npm run build -w $workspace | Write-Host
    if ($LASTEXITCODE -ne 0) { throw "build failed for $workspace" }
  } finally { Pop-Location }

  $stage = Join-Path $BuildDir $workspace
  if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
  New-Item -ItemType Directory -Force $stage | Out-Null
  $src = Join-Path $RepoRoot $srcDir
  Copy-Item (Join-Path $src "dist") -Destination $stage -Recurse
  foreach ($d in $extraDirs) { Copy-Item (Join-Path $src $d) -Destination $stage -Recurse }
  # package.json without devDependencies/scripts: production install only.
  $pkg = Get-Content (Join-Path $src "package.json") -Raw | ConvertFrom-Json
  $prod = [ordered]@{ name = $pkg.name; version = $pkg.version; private = $true; main = "dist/server.js"; dependencies = $pkg.dependencies }
  ($prod | ConvertTo-Json -Depth 5) | Set-Content (Join-Path $stage "package.json") -Encoding ASCII
  Push-Location $stage
  try {
    Invoke-Native npm install --omit=dev --no-audit --no-fund | Write-Host
    if ($LASTEXITCODE -ne 0) { throw "npm install failed for $workspace" }
    $zip = Join-Path $BuildDir "$workspace.zip"
    if (Test-Path $zip) { Remove-Item $zip -Force }
    # bsdtar writes forward-slash paths (Compress-Archive on PS 5.1 writes backslashes, which break on Linux).
    Invoke-Native tar.exe -a -c -f $zip * | Write-Host
    if ($LASTEXITCODE -ne 0) { throw "zip failed for $workspace" }
  } finally { Pop-Location }
  Invoke-Az webapp deploy -g $ResourceGroup -n $app --src-path $zip --type zip --restart true -o none
}

